/**
 * **题目文本（prompt）** —— 纯函数，**不依赖任何重模块**。
 *
 * ⚠️ 为什么单独成文件（2026-11-15）：它原先住在 `run-eval.ts` 里 ⇒
 *   单测 import 那个文件会连带 import MCP/编译器/语言仓那一坨 ⇒
 *   **vitest 直接挂住**（实测：跑一个单测卡了 5 分钟）。
 *   ⇒ prompt 是**评测的尺子** ⇒ 必须能被单测照着 ⇒ 单独成文件。
 */
import type { EvalTask } from './tasks'

export function buildPrompt(
  task: EvalTask,
  rel: string,
  style: string,
  compilerPath?: string,
  opts: { judgeRule?: boolean; envContract?: boolean; hookNotice?: boolean } = {},
): string {
  const JUDGE_RULE = opts.judgeRule !== false
  const ENV_CONTRACT = opts.envContract !== false
  // ⚠️ **hook 通知** —— 「写完会自动编译、诊断已回灌」这句话
  //   ⇒ **默认关**：它是**独立的一个变量**（跟判分口径 / 环境契约分开）
  //   ⇒ ⇒ 开着/关着的差值**全归这一句**。
  //   ⚠️ **为什么值得单独测**：IDE 的 system prompt 里**没有**这句话 ⇒
  //   ⇒ 模型**不知道**写完已经被编译过 ⇒ ⇒ 它会** redundantly **自己去调
  //   `jhyy_check` ⇒ ⇒ 这一句可能就是那几次「多余的验证」。
  const HOOK_NOTICE = opts.hookNotice === true
  // ── **「翻译」题：措辞完全不同** ───────────────────────────────
  //
  // ⚠️ **绝对不能把期望输出给模型** ⇒ 否则它把答案直接打印出来就过
  //   ⇒ 这类题**只判分**（编译 + 退出码 + stdout 逐字）。
  if (task.kind === 'translate') {
    const spec = task.specFile ? 'main.c' : 'main.c'
    // ── **判分口径**：必须告诉模型 ──────────────────────────────
    //
    // ⚠️ **不告诉它 = 模型自己看不到「我过了没有」** ⇒ 它只能靠猜。
    //   实测（2026-11-15，三臂 24 道题的轨迹）:**每一道翻了判分脚本的题，
    //   它的第 1 版就已经通过了** —— 它不知道自己过了 ⇒ 继续找答案：
    //     · 看到自己输出带 `\r\n`（Windows 文本模式），而存下来的期望输出
    //       是 LF ⇒ 怀疑判分不过 ⇒ 去翻 `bench/difftest.py` / `golden.json`
    //       ⇒ 找到 difftest 的**参考实现** ⇒ 直接抄 ⇒ 白烧 5~9 次调用 + 10 轮。
    //   ⇒ 这既是**浪费**，也是**测量失效**（模型靠抄参考实现过的）。
    //
    // ⚠️ **这两句是「环境知识」,不是「语言知识」** ⇒ 放**任务 prompt**,
    //   **不放知识包** —— 放进知识包会把「知识包的效果」和「口径说明」混在一起,
    //   D 臂 vs G 臂的差就分不清是哪个带来的了。
    const judgeRule = JUDGE_RULE
      ? [
          '**判分口径（就这两样，别的都不看）**：',
          '- `stdout` **逐字**相同（同样的行、同样的顺序、同样的数值）；',
          '- 退出码相同（0）；',
          '- ⚠️ **行尾会归一**：`\\r\\n` 与 `\\n` 视为相同 ⇒ 你在 Windows 上跑出来的',
          '  输出带 `\\r\\n` **是正常的、不算不一致**。',
        ]
      : []
    const noPeek = JUDGE_RULE
      ? [
          '- **不要**去翻判分脚本、期望输出、编译器源码 —— 上面那两条就是全部口径，',
          '  本题的一切都在这个工作目录里（`main.c` + 你写的 `main.jhyy`）。',
          '  （去了只会把你带偏：**判定口径不会因为你去翻它而改变**。）',
        ]
      : []
    // ── **环境契约**（2026-11-15 臂 H2 实测逼出来的）────────────────
    //
    // H2（判分口径已加）之后，模型剩下的「探索」**几乎全是找工具链**：
    //   · `which gcc clang cc` / `Get-Command gcc` —— 反复探测 C 编译器在哪
    //   · `find .../Temp -name "*_mcp_run.exe"` —— 想找 MCP 编出来的产物
    //   · `rm -rf .../jhyy-cbuild` —— 猜「构建目录」的名字
    // ⇒ 11 题里 **36 次探索**里 35 次是这一类；另有 **5 次 PowerShell 调用
    //   被自动拒绝**（评测会话没有审批面 ⇒ 没人能批 ⇒ 直接拒）—— 模型在
    //   用 PowerShell 找工具。
    //
    // ⇒ 这些全是**环境契约没讲清** ⇒ 跟判分口径同一类 ⇒ 放**任务 prompt**，
    //   **不放知识包**（知识包是给「语言」用的；gcc 在不在 PATH 上跟语言无关）。
    const envContract = ENV_CONTRACT
      ? [
          '**环境（照这个来，别自己找）**：',
          '- 工作目录里**只有** `main.c`（C 参照）和 `main.jhyy`（你要写的）——',
          '  **别的地方什么都没有，不用去找**。',
          '- **C 参照程序**：`gcc -O0 -o ref_c.exe main.c && ./ref_c.exe` ——',
          '  **gcc 就在 PATH 上** ⇒ 直接用，不用探测它在哪。',
          '- **只有 bash 可用** —— 用 PowerShell 找工具会被**直接拒绝**（没人能批）。',
          '- **JHYY 侧**：`jhyy_run` 已经把 **stdout + 退出码**回显给你了 ⇒',
          '  **不用**去磁盘上找 jhyy.exe 或产物 exe。',
        ]
      : []
    // ⚠️ **hook 通知**（独立变量，默认关）—— 「写完会自动编译、诊断已回灌」
    //   ⇒ 模型**不知道**的话 ⇒ 会** redundantly **自己再调 `jhyy_check`
    //   ⇒ ⇒ 这一句就可能是那几次「多余的验证」。
    const hookNotice = HOOK_NOTICE
      ? [
          '- **写完 `main.jhyy` 会自动编译**：诊断**已经回灌**给你了 ⇒',
          '  **不用**自己再调 `jhyy_check`（除非你要看全部诊断的行号）。',
        ]
      : []
    if (style === 'tight') {
      return [
        `工作目录里有 \`${spec}\` —— 那是**同一个程序的 C 实现**。`,
        '',
        `用 **JHYY** 写一个 \`${rel}\`，**行为跟它完全一致**：`,
        '- **输出逐字相同**（同样的行、同样的顺序、同样的数值）。',
        '- 退出码相同（0）。',
        '',
        `把完整代码写回 \`${rel}\`。`,
        '',
        '**怎么做（照这个来，别绕）**：',
        '1. 先读 `main.c` 搞清它算什么。',
        '2. **注意** JHYY 跟 C 的差别：没有内建 `print`（要先 `extern fn printf` 声明）、',
        '   整数宽度要显式写、整数↔浮点不能隐式转。',
        '3. 用 `jhyy_check` 编译检查 —— 它**一次返回全部诊断**（行:列 + 错误原文）。',
        '4. 用 `jhyy_run` 跑一遍，跟 `main.c` 的输出**逐字比**（行尾不同不算不一致）。',
        '5. 一致 ⇒ **收工，别再改**。',
        '',
        ...judgeRule,
        '',
        ...envContract,
        ...hookNotice,
        '',
        '**范围（重要）**：',
        '- **不要**改 `main.c`。',
        '- **不要**做额外验证（不用探测别的边界）。',
        ...noPeek,
      ].join('\n')
    }
    return [
      `工作目录里有 \`${spec}\` —— 那是**同一个程序的 C 实现**。`,
      '',
      '下面是它的内容：',
      '',
      '```c',
      task.specContent ?? '',
      '```',
      '',
      `用 **JHYY** 写一个 \`${rel}\`，**行为跟它完全一致**：`,
      '- **输出逐字相同**（同样的行、同样的顺序、同样的数值）。',
      '- 退出码相同（0）。',
      '',
      `把完整代码写回 \`${rel}\`。`,
      '你可以用编译器验证，改到它跟 C 版输出一致为止。',
      '',
      ...judgeRule,
      '',
      ...envContract,
      ...hookNotice,
      '',
      ...noPeek,
    ].join('\n')
  }

  // ── **两种破坏方式要两种措辞** ─────────────────────────────────
  //
  // ⚠️ **实测踩过**：behavior-break（能编译、但输出不对）的题，prompt 写「编译不过」
  //   ⇒ 模型**编译一次发现过了 ⇒ 认为没问题 ⇒ 交卷不改**
  //   （实测 C 侧 wrong-format / mask-change 全是「版本数=1」= 模型根本没写文件）。
  // ⇒ 这类题必须说清「**能编译，但输出不对**」，并把**实际输出和期望输出**都给出来。
  const behavior = task.kind === 'behavior-break'
  const opening = behavior
    ? `工作目录里的 \`${rel}\` **能编译，但输出不对**。`
    : `工作目录里的 \`${rel}\` 编译不过。`
  const outputBlock: string[] = []
  if (behavior && task.actualStdout !== undefined) {
    const head = (x: string) => x.split('\n').slice(0, 4).join('\n')
    outputBlock.push(
      '',
      '它现在的输出是：',
      '```',
      head(task.actualStdout),
      '```',
      '',
      '**期望**的输出是：',
      '```',
      head(task.expectStdout ?? ''),
      '```',
    )
  }

  // ── C 对照组：题目措辞跟 JHYY 侧平行，只是语言换了 ──────────────
  if (task.lang === 'c') {
    if (style === 'tight') {
      return [
        opening + '（自己读这个文件看内容）。',
        '',
        behavior
          ? '把它修好：让它**输出跟期望一致**。'
          : '把它修好：让它能编译通过，而且输出跟原来一致。',
        ...outputBlock,
        `把修好的完整代码写回 \`${rel}\`。`,
        '',
        '**怎么做（照这个来，别绕）**：',
        behavior
          ? '1. 先跑一遍看现在的输出（**跟期望比**，找出不一样的地方）。'
          : '1. 先用 Bash 跑 `gcc -O0 -o main.exe ' + rel + '` 编译 —— 它会打印**全部**错误。',
        '2. **只改错误指出的那一处**。',
        '3. 再跑一次确认输出跟期望一致 ⇒ 收工。',
        '',
        '**范围（重要）**：',
        '- **不要**改注释。',
        '- **不要**做额外验证（不用探测别的边界）。',
        '- **不要**顺手修你发现的其他问题。',
      ].join('\n')
    }
    return [
      opening,
      '',
      '下面是它现在的内容：',
      '',
      '```c',
      task.broken,
      '```',
      ...outputBlock,
      '',
      behavior
        ? '把它修好：让它**输出跟期望一致**。'
        : '把它修好：让它能编译通过，而且输出跟原来一致。',
      `把修好的完整代码写回 \`${rel}\`。`,
      '你可以用编译器验证，改到它通过为止。',
    ].join('\n')
  }

  if (style === 'tight') {
    const base = [
      opening + '（自己读这个文件看内容）。',
      '',
      behavior
        ? '把它修好：让它**输出跟期望一致**。'
        : `把它修好：让它能编译通过，而且行为跟原来一致（退出码 ${task.expectExit}）。`,
      ...outputBlock,
      `把修好的完整代码写回 \`${rel}\`。`,
      '',
      '**怎么做（照这个来，别绕）**：',
      behavior
        ? '1. 先用 `jhyy_run` 跑一遍看现在的输出（**跟期望比**，找出不一样的地方）。'
        : '1. 先用 `jhyy_check` 编译检查 —— 它**一次返回全部诊断**（行:列 + 错误原文）。',
      '2. **只改指出的那一处**。',
      '3. 再验一次确认跟期望一致 ⇒ 收工。',
      '',
      '**范围（重要）**：',
      '- **不要**改注释、文档、断言。',
      '- **不要**做额外验证（不用证明断言非空、不用探测别的边界）。',
      '- **不要**顺手修你发现的其他问题。',
    ]
    if (compilerPath) {
      base.push(
        '',
        `编译命令（**直接用这个，别去找**）：`,
        '```',
        `${compilerPath} compile ${rel} -o ${rel.replace(/\.jhyy$/, '')}.out`,
        '```',
      )
    }
    return base.join('\n')
  }

  return [
    opening,
    '',
    '下面是它现在的内容：',
    '',
    '```jhyy',
    task.broken,
    '```',
    ...outputBlock,
    '',
    behavior
      ? '把它修好：让它**输出跟期望一致**。'
      : `把它修好：让它能编译通过，而且行为跟原来一致（退出码 ${task.expectExit}）。`,
    `把修好的完整代码写回 \`${rel}\`。`,
    '你可以用编译器验证，改到它通过为止。',
  ].join('\n')
}
